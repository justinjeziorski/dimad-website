export const CURATED_CITY_BY_ID: Record<string, CuratedCityEntry> = Object.fromEntries(
  CURATED_CITIES.map((entry) => [entry.id, entry])
);

function toRad(deg: number): number {
  return (deg * Math.PI) / 180;
}

export function haversineDistanceKm(
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number {
  const R = 6371;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(toRad(lat1)) *
      Math.cos(toRad(lat2)) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function normalize(str: string): string {
  return str
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}

export function findNearestCuratedCity(
  lat: number,
  lon: number,
  countryFilter?: string
): { city: CuratedCityEntry; distanceKm: number } | null {
  const pool = countryFilter
    ? CURATED_CITIES.filter(
        (c) => normalize(c.country) === normalize(countryFilter)
      )
    : CURATED_CITIES;

  const candidates = pool.length > 0 ? pool : CURATED_CITIES;
  let best: CuratedCityEntry | null = null;
  let bestDist = Infinity;

  for (const entry of candidates) {
    const d = haversineDistanceKm(lat, lon, entry.lat, entry.lon);
    if (d < bestDist) {
      bestDist = d;
      best = entry;
    }
  }

  return best ? { city: best, distanceKm: bestDist } : null;
}

/**
 * Resolves a manually chosen city from the dropdown/picker (when geolocation is off or user overrides).
 * Both greetingPlaceName and programmedCity use the selected curated city.
 */
export function resolveManualCity(cityId: string): ResolvedLocationState {
  const entry = CURATED_CITY_BY_ID[cityId] ?? CURATED_CITIES[0]!;
  return {
    greetingPlaceName: entry.city,
    programmedCity: entry.city,
    stateOrRegion: entry.stateOrRegion,
    country: entry.country,
    timezone: entry.timezone,
    lat: entry.lat,
    lon: entry.lon,
    curatedCityId: entry.id,
    helloOverride: entry.helloOverride,
    source: "manual",
  };
}

/**
 * Resolves geolocation data so the greeting can show the exact detected place
 * (e.g. "Santa Monica") while keeping in-app programmed features anchored to
 * the canonical/curated hub city (e.g. "Los Angeles").
 */
export function resolveGeolocationState(params: {
  detectedCity?: string | null;
  detectedRegion?: string | null;
  detectedCountry?: string | null;
  lat: number;
  lon: number;
  detectedTimezone?: string | null;
  maxSnapDistanceKm?: number;
}): ResolvedLocationState {
  const maxSnapKm = params.maxSnapDistanceKm ?? 120;
  const normDetected = params.detectedCity ? normalize(params.detectedCity) : "";

  const aliasMatch = normDetected
    ? CURATED_CITIES.find((c) => {
        if (normalize(c.city) === normDetected) return true;
        return c.aliases.some((alias) => normalize(alias) === normDetected);
      })
    : undefined;

  const nearest = findNearestCuratedCity(params.lat, params.lon, params.detectedCountry ?? undefined);
  const snappedHub =
    aliasMatch ??
    (nearest && nearest.distanceKm <= maxSnapKm ? nearest.city : null);

  const greetingPlaceName =
    params.detectedCity?.trim() ||
    snappedHub?.city ||
    "Los Angeles";

  const programmedCity = snappedHub?.city || greetingPlaceName;

  return {
    greetingPlaceName,
    programmedCity,
    stateOrRegion: params.detectedRegion?.trim() || snappedHub?.stateOrRegion || "CA",
    country: params.detectedCountry?.trim() || snappedHub?.country || "United States",
    timezone:
      params.detectedTimezone?.trim() ||
      snappedHub?.timezone ||
      "America/Los_Angeles",
    lat: snappedHub ? snappedHub.lat : params.lat,
    lon: snappedHub ? snappedHub.lon : params.lon,
    curatedCityId: snappedHub ? snappedHub.id : null,
    helloOverride: snappedHub?.helloOverride ?? null,
    source: "geolocation",
  };
}
