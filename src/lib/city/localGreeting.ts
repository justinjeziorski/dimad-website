export function getLocalGreeting(
  city?: string | null,
  country?: string | null,
): { word: string; city: string } {
  const rawCity = (city ?? "").trim();
  const displayCity = rawCity.split(",")[0]?.trim() ?? "";
  const cityKey = displayCity.toLowerCase();
  const countryKey = (country ?? "").trim().toLowerCase();

  let word = "Hello";
  if (cityKey && CITY_GREETINGS[cityKey] !== undefined) {
    word = CITY_GREETINGS[cityKey];
  } else if (countryKey && COUNTRY_GREETINGS[countryKey] !== undefined) {
    word = COUNTRY_GREETINGS[countryKey];
  }

  return { word, city: displayCity };
}